/**
 * Player hair sprites — paper-doll hair layer.
 *
 * v1.1 ships only `hairStyle: 'short'`. Other styles in the type union
 * (`long`, `curly`, `bald`) are not yet authored; the composer surfaces
 * the absence via a clear "not yet authored" error.
 *
 * Sprite size: 16 wide × 24 tall (matches body so layers align 1:1).
 *
 * Pixel legend:
 *   .  transparent
 *   K  outline (#000000, literal)
 *   h  hair (@hair slot)
 *
 * Short hair: a cap of hair across the top of the head + small sideburns.
 */

