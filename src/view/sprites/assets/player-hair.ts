export const hairSprites: Record<
  PlayerSkin['hairStyle'],
  Record<PlayerPose, AsciiSprite>
> = {
  short: {
    idle: SHORT_IDLE,
    hit: SHORT_HIT,
    counterattack: SHORT_COUNTERATTACK,
  },
  long: makeUnauthored('long'),
  curly: makeUnauthored('curly'),
  bald: makeUnauthored('bald'),
};

function makeUnauthored(
  style: PlayerSkin['hairStyle'],
): Record<PlayerPose, AsciiSprite> {
  return new Proxy({} as Record<PlayerPose, AsciiSprite>, {
    get(_target, pose: string): AsciiSprite {
      throw new Error(
        `player-hair: hairStyle '${style}' is not yet authored (requested pose '${pose}').`,
      );
    },
  });
}
